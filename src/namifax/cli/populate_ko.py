def populate_ko():
    root_dir = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", ".."))
    po_path = os.path.join(root_dir, "src", "namifax", "locale", "ko", "LC_MESSAGES", "namifax.po")
    mo_path = os.path.join(root_dir, "src", "namifax", "locale", "ko", "LC_MESSAGES", "namifax.mo")

    with open(po_path, "rb") as f:
        catalog = pofile.read_po(f)

    updated_count = 0
    for msg in catalog:
        if not msg.id:
            continue
        msg_id_str = msg.id if isinstance(msg.id, str) else msg.id[0]

        # Exact match in our rich dict
        if msg_id_str in KO_TRANSLATIONS:
            msg.string = KO_TRANSLATIONS[msg_id_str]
            if "fuzzy" in msg.flags:
                msg.flags.discard("fuzzy")
            updated_count += 1
        elif msg.string and "fuzzy" not in msg.flags:
            # Keep existing valid translation
            pass
        else:
            # Check lowercase / trimmed variations
            trimmed = msg_id_str.strip()
            if trimmed in KO_TRANSLATIONS:
                msg.string = KO_TRANSLATIONS[trimmed]
                if "fuzzy" in msg.flags:
                    msg.flags.discard("fuzzy")
                updated_count += 1

    with open(po_path, "wb") as f:
        pofile.write_po(f, catalog)

    with open(mo_path, "wb") as f:
        mofile.write_mo(f, catalog)

    print(f"Updated {updated_count} Korean translations in {po_path}")
    print(f"Compiled binary MO file at {mo_path}")


if __name__ == "__main__":
    populate_ko()
